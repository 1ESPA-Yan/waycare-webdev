// Ícone em linha, do tamanho da fonte e na cor do texto (como o <i> do Font Awesome).
// `nome` usa o padrão do Font Awesome ("fa-droplet"), o mesmo dos JSON de src/data.
function Icone({ nome, className = '', girar = false, ...props }) {
  const Componente = ICONES[nome] || Circle
  if (!ICONES[nome] && import.meta.env.DEV) console.warn(`Ícone sem correspondência no lucide: ${nome}`)
  return (
    <Componente
      size="1em"
      strokeWidth={2.25}
      aria-hidden="true"
      className={`icone${girar ? ' icone-girando' : ''}${className ? ' ' + className : ''}`}
      {...props}
    />
  )
}

export default Icone
